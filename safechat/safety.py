"""Быстрая проверка тревожных сигналов по словам — без ИИ, чтобы работала даже при исчерпанном лимите.

Совпадение — только повод для проверки: дальше ИИ отличает реальный сигнал от гиперболы
(«убью, если опоздаешь 😂»). Если ИИ недоступен, сигнал уходит медиатору на всякий случай.
"""

import re

_PATTERNS = {
    "self_harm": [
        r"не\s+хочу\s+(больше\s+)?жить", r"жить\s+(больше\s+)?не\s+хочу", r"жить\s+не\s+хочется",
        r"поконч(у|ить|ил[аи]?)\s+с\s+собой", r"суицид", r"самоубийств",
        r"убь?ю\s+себя", r"убить\s+себя", r"наложу\s+на\s+себя\s+руки", r"хочу\s+умереть",
        r"лучше\s+бы\s+(я\s+)?(умер|умерла|сдох|сдохла)", r"выйду\s+в\s+окно", r"вскро(юсь|ю\s+вены)",
    ],
    "threat": [
        r"(я\s+)?тебя\s+убью", r"убью\s+тебя", r"прибью\s+тебя", r"зарежу", r"пристрелю",
        r"найду\s+тебя\s+и", r"тебе\s+не\s+жить", r"ноги\s+(тебе\s+)?переломаю", r"закопаю\s+тебя",
    ],
}
_COMPILED = {kind: re.compile("|".join(p), re.IGNORECASE) for kind, p in _PATTERNS.items()}


def detect(text: str) -> str | None:
    """Возвращает тип сигнала ("self_harm" / "threat") или None."""
    normalized = text.lower().replace("ё", "е")
    for kind, pattern in _COMPILED.items():
        if pattern.search(normalized):
            return kind
    return None
