CHAT_KINDS = {
    "work": "💼 Рабочая команда",
    "study": "🎓 Учебная группа",
    "community": "🌐 Сообщество",
    "friends": "👨‍👩‍👧 Друзья, семья",
    "other": "✳️ Другое",
}


def passport_kind(title: str) -> str:
    return f"📝 <b>Паспорт чата «{e(title)}»</b> · шаг 1 из 3\n\nЧто это за чат?"


def passport_purpose(title: str) -> str:
    return (
        f"📝 <b>Паспорт чата «{e(title)}»</b> · шаг 2 из 3\n\n"
        "Для чего этот чат? Напишите одной-двумя фразами.\n\n"
        "<i>Например: «обсуждаем задачи проекта», «общение выпускников 2015 года», "
        "«родительский чат 3 «Б» класса».</i>"
    )


def passport_norms(title: str) -> str:
    return (
        f"📝 <b>Паспорт чата «{e(title)}»</b> · шаг 3 из 3\n\n"
        "Какие нормы общения здесь приняты? Что нормально, а что — уже перебор?\n\n"
        "<i>Например: «общаемся неформально, мат допустим», «жёсткие шутки друг над другом — норма», "
        "«только по делу, на «вы»».</i>"
    )


def passport_done(title: str) -> str:
    return (
        f"Спасибо! Паспорт чата «{e(title)}» сохранён ✅\n\n"
        "Я буду учитывать его при анализе. Изменить паспорт можно в любой момент в разделе «Мои чаты»."
    )


def passport_summary(chat) -> str:
    kind = CHAT_KINDS.get(chat.kind or "", "не указан")
    return (
        f"Тип: {kind}\n"
        f"Цель: {e(chat.purpose) if chat.purpose else 'не указана'}\n"
        f"Нормы общения: {e(chat.norms) if chat.norms else 'не указаны'}"
    )


